package com.bioinfo.phosscope.report;

import com.bioinfo.phosscope.model.AnalysisSettings;
import com.bioinfo.phosscope.model.AnalysisStatus;
import com.bioinfo.phosscope.model.Group;
import com.bioinfo.phosscope.model.ImputationMethod;
import com.bioinfo.phosscope.model.Language;
import com.bioinfo.phosscope.model.SiteStatistic;
import com.bioinfo.phosscope.service.Analysis;

import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.PDPage;
import org.apache.pdfbox.pdmodel.PDPageContentStream;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.pdmodel.font.PDFont;
import org.apache.pdfbox.pdmodel.font.PDType1Font;
import org.apache.pdfbox.pdmodel.font.Standard14Fonts;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * One-page or multi-page PDF report of a differential analysis.
 *
 * <p>The standard Helvetica font is used, so the file needs no embedded font. A character it cannot
 * draw is replaced by {@code ?}. French accents that Helvetica knows (é, è, à, ç…) are kept.
 */
public final class PdfReportWriter {

    /** Address printed at the bottom of every report. */
    public static final String CONTACT_EMAIL = "contact@maximeethier.com";

    /** Page of the consultant who distributes the application. */
    public static final String WEBSITE = "https://www.maximeethier.com";

    /** Support link printed with the contact line. */
    public static final String KOFI = "https://ko-fi.com/K1S228CL7A";

    private static final float MARGIN = 54;
    private static final float LEADING = 14;
    private static final int LINES_PER_PAGE = 46;

    private PdfReportWriter() {}

    /**
     * Renders the report.
     *
     * @param analysis result to describe
     * @param language language of the sentences
     * @param title title typed by the user
     * @param simulated {@code true} when the numbers were generated by PhosScope
     * @return the PDF bytes
     */
    public static byte[] write(
            Analysis analysis, Language language, String title, boolean simulated) {
        Language actual = language == null ? Language.EN : language;
        List<String> lines = lines(analysis, actual, title, simulated);
        try (PDDocument document = new PDDocument()) {
            PDFont regular = new PDType1Font(Standard14Fonts.FontName.HELVETICA);
            PDFont bold = new PDType1Font(Standard14Fonts.FontName.HELVETICA_BOLD);
            int cursor = 0;
            while (cursor < lines.size()) {
                PDPage page = new PDPage(PDRectangle.LETTER);
                document.addPage(page);
                int end = Math.min(lines.size(), cursor + LINES_PER_PAGE);
                writePage(document, page, regular, bold, lines.subList(cursor, end), actual);
                cursor = end;
            }
            ByteArrayOutputStream out = new ByteArrayOutputStream();
            document.save(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void writePage(
            PDDocument document,
            PDPage page,
            PDFont regular,
            PDFont bold,
            List<String> lines,
            Language language)
            throws IOException {
        try (PDPageContentStream stream = new PDPageContentStream(document, page)) {
            float y = page.getMediaBox().getHeight() - MARGIN;
            for (int i = 0; i < lines.size(); i++) {
                PDFont font = i == 0 ? bold : regular;
                float size = i == 0 ? 16 : 10;
                stream.beginText();
                stream.setFont(font, size);
                stream.newLineAtOffset(MARGIN, y);
                stream.showText(encodable(lines.get(i), font));
                stream.endText();
                y -= LEADING;
            }
            stream.beginText();
            stream.setFont(regular, 8);
            stream.newLineAtOffset(MARGIN, 32);
            stream.showText(encodable(footer(language), regular));
            stream.endText();
        }
    }

    static String footer(Language language) {
        if (language == Language.FR) {
            return "Maxime Ethier, consultant en bio-informatique · "
                    + CONTACT_EMAIL
                    + " · "
                    + KOFI;
        }
        return "Maxime Ethier, biocomputing consultant · " + CONTACT_EMAIL + " · " + KOFI;
    }

    /**
     * Sentences of the report, one line each, before they are drawn. Exposed so the wording can be
     * tested without opening the PDF.
     *
     * @param analysis result, or {@code null} for an empty report
     * @param language language of the sentences
     * @param title requested title
     * @param simulated whether the table is simulated
     * @return the lines, never empty
     */
    static List<String> lines(
            Analysis analysis, Language language, String title, boolean simulated) {
        boolean french = language == Language.FR;
        List<String> lines = new ArrayList<>();
        lines.add(cleanTitle(title, french));
        lines.add(
                french
                        ? "PhosScope — phosphorylation différentielle"
                        : "PhosScope — differential phosphorylation");
        if (analysis == null) {
            lines.add(french ? "Aucune analyse." : "No analysis.");
            return lines;
        }
        lines.add(
                (french ? "Fichier : " : "File: ")
                        + analysis.fileName()
                        + " ("
                        + analysis.format()
                        + ")");
        if (simulated) {
            lines.add(
                    french
                            ? "Données simulées par PhosScope, pour la démonstration."
                            : "Data simulated by PhosScope, for the demonstration.");
        }
        lines.add(groups(analysis, french));
        lines.add(cleaning(analysis, french));
        lines.add(imputation(analysis.settings(), french));
        lines.add(thresholds(analysis.settings(), french));
        lines.add(status(analysis, french));
        if (!analysis.sites().isEmpty()) {
            lines.add("");
            lines.add(
                    french
                            ? "Sites testés (les plus significatifs d'abord)"
                            : "Tested sites (most significant first)");
            lines.add(
                    french
                            ? "Gène  Site  log2 FC  p  q  Appel"
                            : "Gene  Site  log2 FC  p  q  Call");
            int shown = 0;
            for (SiteStatistic site : analysis.sites()) {
                if (shown == 40) {
                    lines.add(
                            french
                                    ? "… tableau limité aux 40 premières lignes."
                                    : "… table limited to the first 40 rows.");
                    break;
                }
                lines.add(siteLine(site, french));
                shown++;
            }
        }
        lines.add("");
        lines.add(
                french
                        ? "Disponible pour des contrats ou un emploi en bio-informatique."
                        : "Available for bioinformatics contracts or employment.");
        lines.add(WEBSITE);
        return lines;
    }

    private static String cleanTitle(String title, boolean french) {
        String fallback = french ? "Rapport PhosScope" : "PhosScope report";
        if (title == null || title.isBlank()) {
            return fallback;
        }
        String oneLine = title.replace('\n', ' ').replace('\r', ' ').trim();
        if (oneLine.length() > 80) {
            return oneLine.substring(0, 80);
        }
        return oneLine;
    }

    private static String groups(Analysis analysis, boolean french) {
        int control = 0;
        int disease = 0;
        for (String name : analysis.sampleNames()) {
            Group group = analysis.settings().groups().get(name);
            if (group == Group.CONTROL) {
                control++;
            } else if (group == Group.DISEASE) {
                disease++;
            }
        }
        if (french) {
            return "Échantillons : " + control + " témoin, " + disease + " malade.";
        }
        return "Samples: " + control + " control, " + disease + " disease.";
    }

    private static String cleaning(Analysis analysis, boolean french) {
        if (french) {
            return "Lignes lues "
                    + analysis.sitesRead()
                    + ", contaminants "
                    + analysis.droppedContaminant()
                    + ", leurres "
                    + analysis.droppedReverse()
                    + ", seul le site "
                    + analysis.droppedOnlyBySite()
                    + ", localisation "
                    + analysis.droppedLocalization()
                    + ", trop de manquants "
                    + analysis.droppedMissing()
                    + ".";
        }
        return "Rows read "
                + analysis.sitesRead()
                + ", contaminants "
                + analysis.droppedContaminant()
                + ", decoys "
                + analysis.droppedReverse()
                + ", only by site "
                + analysis.droppedOnlyBySite()
                + ", localization "
                + analysis.droppedLocalization()
                + ", too missing "
                + analysis.droppedMissing()
                + ".";
    }

    private static String imputation(AnalysisSettings settings, boolean french) {
        ImputationMethod method = settings.imputation();
        if (method == ImputationMethod.NONE) {
            return french
                    ? "Imputation : aucune (sites incomplets exclus)."
                    : "Imputation: none (incomplete sites excluded).";
        }
        if (method == ImputationMethod.HALF_MINIMUM) {
            return french
                    ? "Imputation : moitié du minimum observé de l'échantillon (log2 − 1)."
                    : "Imputation: half the lowest observed value of the sample (log2 − 1).";
        }
        String numbers =
                String.format(
                        Locale.ROOT,
                        "%.2f / %.2f, seed %d",
                        settings.downshift(),
                        settings.width(),
                        settings.seed());
        if (french) {
            return "Imputation de Perseus (décalage / largeur " + numbers + ").";
        }
        return "Perseus imputation (downshift / width " + numbers + ").";
    }

    private static String thresholds(AnalysisSettings settings, boolean french) {
        String fdr = String.format(Locale.ROOT, "%.3f", settings.fdr());
        String fold = String.format(Locale.ROOT, "%.2f", settings.minAbsLog2FoldChange());
        if (french) {
            return "Seuils : q ≤ " + fdr + " et |log2 FC| ≥ " + fold + ".";
        }
        return "Thresholds: q ≤ " + fdr + " and |log2 FC| ≥ " + fold + ".";
    }

    private static String status(Analysis analysis, boolean french) {
        AnalysisStatus status = analysis.status();
        if (status == AnalysisStatus.NEED_GROUPS) {
            return french
                    ? "Les deux groupes ne sont pas encore assignés."
                    : "The two groups are not both assigned yet.";
        }
        if (status == AnalysisStatus.NEED_REPLICATES) {
            return french
                    ? "Chaque groupe doit contenir au moins deux échantillons."
                    : "Each group needs at least two samples.";
        }
        if (status == AnalysisStatus.NO_SITE) {
            return french ? "Aucun site ne peut être testé." : "No site can be tested.";
        }
        if (french) {
            return "Sites testés "
                    + analysis.sites().size()
                    + ", significatifs "
                    + analysis.significantCount()
                    + ".";
        }
        return "Tested sites "
                + analysis.sites().size()
                + ", significant "
                + analysis.significantCount()
                + ".";
    }

    private static String siteLine(SiteStatistic site, boolean french) {
        String call;
        if (!site.significant()) {
            call = french ? "non" : "no";
        } else if (site.log2FoldChange() > 0) {
            call = french ? "hausse" : "up";
        } else {
            call = french ? "baisse" : "down";
        }
        return site.gene()
                + "  "
                + site.siteLabel()
                + "  "
                + String.format(Locale.ROOT, "%.2f", site.log2FoldChange())
                + "  "
                + String.format(Locale.ROOT, "%.3g", site.pValue())
                + "  "
                + String.format(Locale.ROOT, "%.3g", site.qValue())
                + "  "
                + call;
    }

    static String encodable(String value, PDFont font) throws IOException {
        StringBuilder out = new StringBuilder();
        String text = value == null ? "" : value;
        for (int i = 0; i < text.length(); ) {
            int point = text.codePointAt(i);
            String character = new String(Character.toChars(point));
            try {
                font.encode(character);
                out.append(character);
            } catch (IllegalArgumentException | IOException e) {
                out.append('?');
            }
            i += Character.charCount(point);
        }
        return out.toString();
    }
}
