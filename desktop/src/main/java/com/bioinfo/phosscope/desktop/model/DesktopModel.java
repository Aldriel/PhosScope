package com.bioinfo.phosscope.desktop.model;

import com.bioinfo.phosscope.desktop.prefs.UserPreferences;
import com.bioinfo.phosscope.example.SimulatedCohort;
import com.bioinfo.phosscope.model.AnalysisSettings;
import com.bioinfo.phosscope.model.Group;
import com.bioinfo.phosscope.model.ImputationMethod;
import com.bioinfo.phosscope.model.Language;
import com.bioinfo.phosscope.model.QuantTable;
import com.bioinfo.phosscope.parse.ParseException;
import com.bioinfo.phosscope.service.Analysis;
import com.bioinfo.phosscope.service.PhosService;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * State of the desktop application: the open table, the settings and the latest analysis.
 *
 * <p>The view never calls {@link PhosService}. A method that rejects a value returns the error code
 * and leaves the previous settings in place.
 */
public final class DesktopModel {

    private final PhosService service;
    private final UserPreferences preferences;
    private QuantTable table;
    private AnalysisSettings settings;
    private Analysis analysis;
    private boolean simulated;
    private String errorCode;
    private int fontSize;

    /**
     * Model that remembers language and text size in {@code preferences}.
     *
     * @param service shared model
     * @param preferences user preferences
     */
    public DesktopModel(PhosService service, UserPreferences preferences) {
        this.service = service;
        this.preferences = preferences;
        this.fontSize = preferences.fontSize();
    }

    /** Opens the simulated cohort. */
    public void openExample() {
        open(SimulatedCohort.bytes(), SimulatedCohort.FILE_NAME, true);
    }

    /**
     * Opens a file.
     *
     * @param content file bytes
     * @param name file name
     * @param simulatedData {@code true} only for the built-in example
     */
    public void open(byte[] content, String name, boolean simulatedData) {
        try {
            table = service.read(content, name);
            settings = AnalysisSettings.defaultsFor(table.sampleNames());
            simulated = simulatedData;
            errorCode = null;
            rerun();
        } catch (ParseException e) {
            table = null;
            settings = null;
            analysis = null;
            simulated = false;
            errorCode = e.code();
        }
    }

    /** Parsed table, or {@code null}. */
    public QuantTable table() {
        return table;
    }

    /** Latest analysis, or {@code null} when no table is open. */
    public Analysis analysis() {
        return analysis;
    }

    /** Settings, or {@code null} before a table is open. */
    public AnalysisSettings settings() {
        return settings;
    }

    /** Whether the open table was generated by PhosScope. */
    public boolean simulated() {
        return simulated;
    }

    /** Code of the last error, or {@code null}. */
    public String errorCode() {
        return errorCode;
    }

    /** Current language. */
    public Language language() {
        return preferences.language();
    }

    /** Remembers a new language. */
    public void language(Language language) {
        preferences.language(language);
    }

    /** Current text size, in pixels. */
    public int fontSize() {
        return fontSize;
    }

    /** Changes the text size by one pixel, inside the allowed range. */
    public void changeFont(int delta) {
        fontSize(fontSize + delta);
    }

    /** Restores the default text size. */
    public void resetFont() {
        fontSize(UserPreferences.DEFAULT_FONT);
    }

    /** Sets an exact text size. */
    public void fontSize(int size) {
        fontSize = UserPreferences.clamp(size);
        preferences.fontSize(fontSize);
    }

    /**
     * Assigns a sample to a group.
     *
     * @param sample sample name
     * @param group new group
     */
    public void setGroup(String sample, Group group) {
        if (settings == null) {
            return;
        }
        Map<String, Group> groups = new LinkedHashMap<>(settings.groups());
        groups.put(sample, group);
        settings = settings.toBuilder().groups(groups).build();
        rerun();
    }

    /** Replaces the cleaning choices. Returns an error code, or {@code null}. */
    public String setCleaning(
            boolean contaminants,
            boolean reverse,
            boolean onlySite,
            double localization,
            int minValid) {
        if (settings == null) {
            return "NO_TABLE";
        }
        return update(
                settings.toBuilder()
                        .dropContaminants(contaminants)
                        .dropReverse(reverse)
                        .dropOnlyBySite(onlySite)
                        .minLocalization(localization)
                        .minValidPerGroup(minValid));
    }

    /** Replaces the imputation choices. Returns an error code, or {@code null}. */
    public String setImputation(
            ImputationMethod method, double downshift, double width, long seed) {
        if (settings == null) {
            return "NO_TABLE";
        }
        return update(
                settings.toBuilder()
                        .imputation(method)
                        .downshift(downshift)
                        .width(width)
                        .seed(seed));
    }

    /** Replaces the significance thresholds. Returns an error code, or {@code null}. */
    public String setThresholds(double fdr, double foldChange) {
        if (settings == null) {
            return "NO_TABLE";
        }
        return update(settings.toBuilder().fdr(fdr).minAbsLog2FoldChange(foldChange));
    }

    /**
     * PDF report of the current analysis.
     *
     * @param title title typed by the user
     * @return the PDF, or {@code null} when nothing is open
     */
    public byte[] report(String title) {
        if (analysis == null) {
            return null;
        }
        return service.report(analysis, preferences.language(), title, simulated);
    }

    /** Tab-separated results, or an empty header when nothing is open. */
    public String export() {
        return service.exportTable(analysis, preferences.language());
    }

    private String update(AnalysisSettings.Builder builder) {
        try {
            settings = builder.build();
            errorCode = null;
            rerun();
            return null;
        } catch (IllegalArgumentException e) {
            errorCode = e.getMessage();
            return errorCode;
        }
    }

    private void rerun() {
        analysis = service.analyze(table, settings);
    }
}
