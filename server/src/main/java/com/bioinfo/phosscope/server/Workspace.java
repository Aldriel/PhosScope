package com.bioinfo.phosscope.server;

import com.bioinfo.phosscope.model.AnalysisSettings;
import com.bioinfo.phosscope.model.QuantTable;

/**
 * One visitor's table and settings. The uploaded bytes are not kept: only the parsed table is, and
 * only in memory.
 */
public final class Workspace {

    private final String id;
    private QuantTable table;
    private AnalysisSettings settings;
    private boolean simulated;
    private long touchedMillis;

    /**
     * Creates an empty workspace.
     *
     * @param id random identifier
     * @param touchedMillis current time, in milliseconds
     */
    public Workspace(String id, long touchedMillis) {
        this.id = id;
        this.touchedMillis = touchedMillis;
    }

    /** Identifier sent to the browser. */
    public String id() {
        return id;
    }

    /** Parsed table, or {@code null} when the visitor has not opened a file yet. */
    public QuantTable table() {
        return table;
    }

    /** Settings, or {@code null} before a table is opened. */
    public AnalysisSettings settings() {
        return settings;
    }

    /** Whether the table was generated by PhosScope. */
    public boolean simulated() {
        return simulated;
    }

    /** Last time the visitor used this workspace, in milliseconds. */
    public long touchedMillis() {
        return touchedMillis;
    }

    /** Replaces the table and marks the workspace as just used. */
    public void table(
            QuantTable table, AnalysisSettings settings, boolean simulated, long touchedMillis) {
        this.table = table;
        this.settings = settings;
        this.simulated = simulated;
        this.touchedMillis = touchedMillis;
    }

    /** Replaces the settings. */
    public void settings(AnalysisSettings settings, long touchedMillis) {
        this.settings = settings;
        this.touchedMillis = touchedMillis;
    }

    /** Notes that the visitor is still here. */
    public void touch(long touchedMillis) {
        this.touchedMillis = touchedMillis;
    }
}
